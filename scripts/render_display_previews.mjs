function parseIcons(headerText) {
  const icons = {};
  const dimRe =
    /static constexpr int16_t (kIcon\w+)W = (\d+);\s*\nstatic constexpr int16_t \1H = (\d+);/g;
  let m;
  while ((m = dimRe.exec(headerText))) {
    icons[m[1]] = {
      w: Number(m[2]),
      h: Number(m[3]),
      bytes: null,
    };
  }
  const arrRe =
    /static const uint8_t (kIcon\w+)\[\] PROGMEM = \{([^}]+)\};/g;
  while ((m = arrRe.exec(headerText))) {
    const name = m[1];
    if (!icons[name]) {
      throw new Error(`Bitmap for unknown icon ${name}`);
    }
    icons[name].bytes = Uint8Array.from(
      [...m[2].matchAll(/0x([0-9A-Fa-f]{2})/g)].map((x) => parseInt(x[1], 16)),
    );
  }
  for (const [name, icon] of Object.entries(icons)) {
    if (!icon.bytes) {
      throw new Error(`Missing bitmap bytes for ${name}`);
    }
  }
  return icons;
}

function createFrame(fill = "white") {
  const px = new Array(PANEL * PANEL);
  const c = COLORS[fill];
  for (let i = 0; i < px.length; i++) {
    px[i] = c;
  }
  return px;
}

function setPixel(frame, x, y, colorName) {
  if (x < 0 || y < 0 || x >= PANEL || y >= PANEL) {
    return;
  }
  frame[y * PANEL + x] = COLORS[colorName];
}

function drawBitmap(frame, x0, y0, icon, colorName) {
  const rowBytes = Math.ceil(icon.w / 8);
  for (let y = 0; y < icon.h; y++) {
    for (let x = 0; x < icon.w; x++) {
      const byte = icon.bytes[y * rowBytes + (x >> 3)];
      if (byte & (0x80 >> (x & 7))) {
        setPixel(frame, x0 + x, y0 + y, colorName);
      }
    }
  }
}

function textBounds(text, size) {
  return {
    x1: 0,
    y1: 0,
    w: text.length * 6 * size,
    h: 8 * size,
  };
}

function drawChar(frame, x, y, ch, size, colorName) {
  const c = ch.charCodeAt(0) & 0xff;
  for (let i = 0; i < 5; i++) {
    let line = GLCD_FONT[c * 5 + i];
    for (let j = 0; j < 8; j++) {
      if (line & 0x01) {
        if (size === 1) {
          setPixel(frame, x + i, y + j, colorName);
        } else {
          for (let yy = 0; yy < size; yy++) {
            for (let xx = 0; xx < size; xx++) {
              setPixel(frame, x + i * size + xx, y + j * size + yy, colorName);
            }
          }
        }
      }
      line >>= 1;
    }
  }
}

function drawText(frame, x, y, text, size, colorName) {
  let cursor = x;
  for (const ch of text) {
    drawChar(frame, cursor, y, ch, size, colorName);
    cursor += 6 * size;
  }
}

function drawCenteredText(frame, text, startSize, minSize, colorName) {
  let textSize = startSize;
  let bounds;
  for (;;) {
    bounds = textBounds(text, textSize);
    if (bounds.w <= PANEL - 8 && bounds.h <= PANEL - 8) {
      break;
    }
    if (textSize <= minSize) {
      break;
    }
    textSize--;
  }
  const cursorX = Math.floor((PANEL - bounds.w) / 2) - bounds.x1;
  const cursorY = Math.floor((PANEL - bounds.h) / 2) - bounds.y1;
  drawText(frame, cursorX, cursorY, text, textSize, colorName);
  return { textSize, bounds, cursorX, cursorY };
}

function batteryIconName(pct) {
  if (pct >= 80) return "kIconBatteryFull";
  if (pct >= 40) return "kIconBatteryMedium";
  if (pct >= 15) return "kIconBatteryLow";
  return "kIconBatteryEmpty";
}

function batteryColor(pct) {
  if (pct < 15) return "red";
  if (pct < 40) return "yellow";
  return "black";
}

function drawBatteryTopRight(frame, icons, pct) {
  const icon = icons[batteryIconName(pct)];
  const x = PANEL - RIGHT_MARGIN - icons.kIconBatteryFull.w;
  drawBitmap(frame, x, BATTERY_TOP, icon, batteryColor(pct));
}

function footerTextSize(digitLen) {
  return digitLen <= 3 ? 4 : 3;
}

function drawHeartOnline(icons, { rx = 42, tx = 7, battery = 92 } = {}) {
  const frame = createFrame();
  const heart = icons.kIconHeart;
  const heartX = Math.floor((PANEL - heart.w) / 2);
  const heartY = FOOTER_TEXT_TOP - heart.h - HEART_FOOTER_GAP;
  drawBitmap(frame, heartX, heartY, heart, "red");

  const arrowLane = icons.kIconMoveDown.w + 5;
  const recvBuf = String(rx);
  const sentBuf = String(tx);
  const recvSize = footerTextSize(Math.max(recvBuf.length, 1));
  const sentSize = footerTextSize(Math.max(sentBuf.length, 1));
  const recvBounds = textBounds(recvBuf, recvSize);
  const sentBounds = textBounds(sentBuf, sentSize);
  const recvX = LEFT_MARGIN + arrowLane - recvBounds.x1;
  const sentTrailingBlankPx = sentSize;
  const sentX =
    PANEL - RIGHT_MARGIN - arrowLane - sentBounds.w - sentBounds.x1 + sentTrailingBlankPx;

  drawBitmap(frame, LEFT_MARGIN, FOOTER_TEXT_TOP, icons.kIconMoveDown, "black");
  drawBitmap(
    frame,
    PANEL - RIGHT_MARGIN - icons.kIconMoveUp.w,
    FOOTER_TEXT_TOP,
    icons.kIconMoveUp,
    "black",
  );
  drawText(frame, recvX, FOOTER_TEXT_TOP, recvBuf, recvSize, "black");
  drawText(frame, sentX, FOOTER_TEXT_TOP, sentBuf, sentSize, "black");
  drawBatteryTopRight(frame, icons, battery);
  return frame;
}

function drawHeartOffline(icons, { battery = 55 } = {}) {
  const frame = createFrame();
  const heart = icons.kIconHeartCrack;
  const heartX = Math.floor((PANEL - heart.w) / 2);
  const heartY = Math.floor((PANEL - heart.h) / 2);
  drawBitmap(frame, heartX, heartY, heart, "red");
  drawBatteryTopRight(frame, icons, battery);
  return frame;
}

function drawProductTitle(icons, { battery = 88 } = {}) {
  const frame = createFrame();
  drawCenteredText(frame, "Chaya2MQTT", 3, 1, "red");
  drawBatteryTopRight(frame, icons, battery);
  return frame;
}

function drawPowerOff(icons) {
  const frame = createFrame();
  const title = "Chaya2MQTT";
  const titleSize = 3;
  const gap = 10;
  const visualTopInset = 7;
  const titleTop = gap;
  const bounds = textBounds(title, titleSize);
  const titleX = Math.floor((PANEL - bounds.w) / 2) - bounds.x1;
  const heart = icons.kIconHeartOff;
  const heartX = Math.floor((PANEL - heart.w) / 2);
  const heartY = titleTop + bounds.h + gap - visualTopInset;
  drawText(frame, titleX, titleTop, title, titleSize, "red");
  drawBitmap(frame, heartX, heartY, heart, "black");
  return frame;
}

function drawSetupQr(icons, qrModules) {
  const frame = createFrame();
  const title = "Chaya2MQTT";
  const quiet = 4;
  const qrSize = qrModules.length;
  const totalMods = qrSize + 2 * quiet;
  let scale = Math.floor(Math.min(PANEL, PANEL) / totalMods);
  if (scale < 1) scale = 1;
  const drawn = totalMods * scale;
  const originX = Math.floor((PANEL - drawn) / 2);
  const qrPx = qrSize * scale;

  let titleSize = 3;
  let bounds;
  for (;;) {
    bounds = textBounds(title, titleSize);
    const free = PANEL - qrPx - bounds.h;
    if (bounds.w <= PANEL - 4 && free >= 8) {
      break;
    }
    if (titleSize <= 1) break;
    titleSize--;
  }
  // Equal thirds: title↔top frame, title↔QR, QR↔bottom frame (matches firmware).
  const free = Math.max(0, PANEL - qrPx - bounds.h);
  const outerPad = Math.floor(free / 3);
  const titleX = Math.floor((PANEL - bounds.w) / 2) - bounds.x1;
  const titleY = outerPad - bounds.y1;
  const originY = PANEL - outerPad - qrPx;
  drawText(frame, titleX, titleY, title, titleSize, "red");

  for (let y = 0; y < qrSize; y++) {
    for (let x = 0; x < qrSize; x++) {
      if (!qrModules[y][x]) continue;
      const px = originX + (x + quiet) * scale;
      const py = originY + y * scale;
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          setPixel(frame, px + dx, py + dy, "black");
        }
      }
    }
  }
  return frame;
}

function scaleFrame(frame, scale) {
  const w = PANEL * scale;
  const h = PANEL * scale;
  const out = Buffer.alloc(w * h * 3);
  for (let y = 0; y < PANEL; y++) {
    for (let x = 0; x < PANEL; x++) {
      const [r, g, b] = frame[y * PANEL + x];
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          const i = ((y * scale + dy) * w + (x * scale + dx)) * 3;
          out[i] = r;
          out[i + 1] = g;
          out[i + 2] = b;
        }
      }
    }
  }
  return { width: w, height: h, rgb: out };
}

function crc32(buf) {
  let c = ~0;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? (0xedb88320 ^ (c >>> 1)) : c >>> 1;
    }
  }
  return ~c >>> 0;
}

function pngChunk(type, data) {
  const typeBuf = Buffer.from(type, "ascii");
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const crcBuf = Buffer.alloc(4);
  crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([len, typeBuf, data, crcBuf]);
}

function writePng(filePath, width, height, rgb) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 2; // RGB
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;

  const stride = width * 3;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0;
    rgb.copy(raw, y * (stride + 1) + 1, y * stride, y * stride + stride);
  }
  const idat = zlib.deflateSync(raw, { level: 9 });
  const png = Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk("IHDR", ihdr),
    pngChunk("IDAT", idat),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
  fs.writeFileSync(filePath, png);
}

function savePreview(name, frame) {
  const { width, height, rgb } = scaleFrame(frame, SCALE);
  const filePath = path.join(outDir, `${name}.png`);
  writePng(filePath, width, height, rgb);
  console.log(`  wrote ${path.relative(repoRoot, filePath)} (${width}×${height})`);
}

async function loadQrModules(payload) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "chaya-display-preview-"));
  try {
    execFileSync("npm", ["init", "-y"], { cwd: tmp, stdio: "ignore" });
    execFileSync("npm", ["install", "qrcode@1.5.4"], { cwd: tmp, stdio: "inherit" });
    const QRCode = (await import(path.join(tmp, "node_modules/qrcode/lib/index.js"))).default;
    // Match firmware: ECC-M, auto version (payload fits version 3).
    const qr = QRCode.create(payload, { errorCorrectionLevel: "M" });
    const size = qr.modules.size;
    const modules = [];
    for (let y = 0; y < size; y++) {
      const row = [];
      for (let x = 0; x < size; x++) {
        row.push(qr.modules.get(x, y));
      }
      modules.push(row);
    }
    return modules;
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

async function main() {
  const headerText = fs.readFileSync(iconsHeader, "utf8");
  const icons = parseIcons(headerText);
  fs.mkdirSync(outDir, { recursive: true });

  console.log("Rendering display previews…");
  savePreview("heart-online", drawHeartOnline(icons, { rx: 42, tx: 17, battery: 92 }));
  savePreview("heart-offline", drawHeartOffline(icons));
  savePreview("product-title", drawProductTitle(icons));
  savePreview("power-off", drawPowerOff(icons));

  // Sample SoftAP credentials — illustrative only (not a live PIN).
  const qrPayload = "WIFI:T:WPA;S:Chaya2MQTT;P:12345678;;";
  const modules = await loadQrModules(qrPayload);
  savePreview("setup-qr", drawSetupQr(icons, modules));
  console.log("Done.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
